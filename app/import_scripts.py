"""Import built-in scripts from a markdown file in the TAXONOMY.md §4 format.

    python -m app.import_scripts docs/rewrite/SCRIPTS_NEW.md            # dry run: report only
    python -m app.import_scripts docs/rewrite/SCRIPTS_NEW.md --apply    # write app/script_texts.py
                                                                        # and refresh the local database

A script is a heading "### `slug` — Title" followed by a ```text block. Lines outside
blocks are ignored. Scripts in the code but missing from the file are kept. In the
database, scripts the user edited in the app stay as they are unless --overwrite-edited.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

from . import script_templates as taxonomy

TEXTS_FILE = Path(__file__).with_name("script_texts.py")
HEADING = re.compile(r"^###\s+`([^`]+)`\s*(?:[—–:-]\s*)?(.*?)\s*$")
# Any heading that names a slug in backticks; one HEADING does not match is reported, not skipped.
SLUG_HEADING = re.compile(r"^#{2,4}\s*`[^`]+`")
FENCE_OPEN = re.compile(r"^```text\s*$")
FENCE_CLOSE = re.compile(r"^```\s*$")
BRACKETS = re.compile(r"\[[^\]\n]+\]")
TITLE_LIMIT = 60


@dataclass
class Parsed:
    scripts: dict[str, tuple[str, str]] = field(default_factory=dict)  # slug → (title, body)
    unknown: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def parse(text: str) -> Parsed:
    result = Parsed()
    lines = text.lstrip("\ufeff").replace("\r\n", "\n").split("\n")
    heading: tuple[str, str, int] | None = None
    index = 0
    while index < len(lines):
        line = lines[index]
        match = HEADING.match(line)
        if not match and SLUG_HEADING.match(line):
            result.errors.append(f"строка {index + 1}: заголовок не разобран, нужен «### `slug` — Название»")
        if match:
            if heading:
                result.errors.append(f"строка {heading[2]}: у `{heading[0]}` нет блока ```text")
            heading = (match.group(1).strip(), (match.group(2) or "").strip(), index + 1)
            index += 1
            continue
        if FENCE_OPEN.match(line) and heading:
            body_lines = []
            index += 1
            while index < len(lines) and not FENCE_CLOSE.match(lines[index]):
                body_lines.append(lines[index])
                index += 1
            if index >= len(lines):
                result.errors.append(f"строка {heading[2]}: блок `{heading[0]}` не закрыт ```")
            _add(result, heading, "\n".join(body_lines).strip())
            heading = None
        index += 1
    if heading:
        result.errors.append(f"строка {heading[2]}: у `{heading[0]}` нет блока ```text")
    return result


def _add(result: Parsed, heading: tuple[str, str, int], body: str) -> None:
    slug, title, line = heading
    meta = taxonomy.parse_slug(slug)
    if not meta:
        result.unknown.append(slug)
        return
    if slug in result.scripts:
        result.errors.append(f"строка {line}: `{slug}` встречается дважды, оставлен первый")
        return
    if not body:
        result.errors.append(f"строка {line}: у `{slug}` пустой текст")
        return
    title = " ".join(title.split()) or taxonomy.default_title(*meta)
    if len(title) > TITLE_LIMIT:
        result.warnings.append(f"`{slug}`: название длиннее {TITLE_LIMIT} символов, обрезано")
        title = title[:TITLE_LIMIT].rstrip()
    brackets = BRACKETS.findall(body)
    if meta[1] in {"first", "reminder"} and brackets:
        result.warnings.append(f"`{slug}`: в этапе {meta[1]} не должно быть [скобок], найдено {len(brackets)}")
    elif len(brackets) > 1:
        result.warnings.append(f"`{slug}`: [скобок] {len(brackets)}, по контракту не больше одной")
    result.scripts[slug] = (title, body)


@dataclass
class Plan:
    added: list[str]
    changed: list[str]
    unchanged: list[str]
    kept: list[str]          # in code, not in the file
    merged: dict[str, tuple[str, str]]


def plan(parsed: Parsed, current: dict[str, tuple[str, str]]) -> Plan:
    added = [slug for slug in parsed.scripts if slug not in current]
    changed = [slug for slug in parsed.scripts if slug in current and parsed.scripts[slug] != current[slug]]
    unchanged = [slug for slug in parsed.scripts if current.get(slug) == parsed.scripts[slug]]
    kept = [slug for slug in current if slug not in parsed.scripts]
    merged = {**current, **parsed.scripts}
    return Plan(added, changed, unchanged, kept, taxonomy._ordered(merged))


def render_module(texts: dict[str, tuple[str, str]]) -> str:
    lines = ['"""Built-in script texts. Generated by `python -m app.import_scripts`; edit the markdown',
             'file and re-import instead of editing by hand. Slugs follow docs/rewrite/TAXONOMY.md."""',
             "", "TEXTS = {"]
    for slug, (title, body) in texts.items():
        lines.append(f"    {slug!r}: (")
        lines.append(f"        {title!r},")
        lines.append(f"        {body!r},")
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def edited_in_db(slugs, path=None) -> list[str]:
    """Slugs whose text the user changed in the app (body no longer matches the shipped one)."""
    from . import db
    target = path or db.DB_PATH
    if not Path(target).is_file():
        return []
    with db.connection(target) as conn:
        columns = {row[1] for row in conn.execute("PRAGMA table_info(templates)")}
        if "default_hash" not in columns:
            return []
        rows = conn.execute("SELECT slug,body,default_hash FROM templates WHERE origin='builtin'").fetchall()
    wanted = set(slugs)
    return [row["slug"] for row in rows
            if row["slug"] in wanted and taxonomy.body_hash(row["body"]) != row["default_hash"]]


def missing_categories(parsed: Parsed, result: Plan) -> list[str]:
    """Categories the file has no script for, with what stays in their place (e.g. landing sent later)."""
    present = {taxonomy.parse_slug(slug)[0] for slug in parsed.scripts}
    lines = []
    for key, (title, _) in taxonomy.CATEGORIES.items():
        if key in present:
            continue
        kept = [slug for slug in result.kept if taxonomy.parse_slug(slug)[0] == key]
        lines.append(f"{key} — {title}: " + (f"временные тексты оставлены ({', '.join(kept)})" if kept
                                               else "текстов нет, первое сообщение в карточке будет пустым"))
    return lines


def report(parsed: Parsed, result: Plan, edited: list[str], applied: bool) -> str:
    def block(title, items):
        return [f"{title}: {len(items)}"] + [f"  · {item}" for item in items]
    out = ["Импорт применён." if applied else "Пробный прогон: ничего не записано. Добавьте --apply, чтобы применить.",
           f"Скриптов в файле: {len(parsed.scripts)}"]
    out += block("Добавлено", result.added)
    out += block("Изменено", result.changed)
    out.append(f"Без изменений: {len(result.unchanged)}")
    out += block("Неизвестные slug-и (пропущены)", parsed.unknown)
    out += block("Есть в коде, нет в файле (оставлены)", result.kept)
    out += block("Категорий нет в файле (остаются текущие тексты)", missing_categories(parsed, result))
    out += block("Правлены в приложении (в базе не меняются без --overwrite-edited)", edited)
    out += block("Ошибки", parsed.errors)
    out += block("Предупреждения", parsed.warnings)
    return "\n".join(out)


def apply(result: Plan, *, db_path=None, overwrite_edited: bool = False, texts_file: Path | None = None) -> None:
    (texts_file or TEXTS_FILE).write_text(render_module(result.merged), encoding="utf-8", newline="\n")
    from . import db
    target = Path(db_path or db.DB_PATH)
    if target.is_file():
        db.sync_builtin_templates(target, result.merged, overwrite_edited=overwrite_edited)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.import_scripts", description=__doc__.split("\n")[0])
    parser.add_argument("file", type=Path)
    parser.add_argument("--apply", action="store_true", help="записать app/script_texts.py и обновить базу")
    parser.add_argument("--db", type=Path, help="путь к базе (по умолчанию база приложения)")
    parser.add_argument("--overwrite-edited", action="store_true", help="заменить и правленые в приложении тексты")
    args = parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parsed = parse(args.file.read_text(encoding="utf-8-sig"))
    result = plan(parsed, dict(taxonomy.TEMPLATES))
    touched = result.added + result.changed
    edited = edited_in_db(touched, args.db)
    if args.apply and parsed.errors:
        print(report(parsed, result, edited, applied=False))
        print("\nЕсть ошибки разбора: исправьте файл, импорт не применён.")
        return 1
    if args.apply:
        apply(result, db_path=args.db, overwrite_edited=args.overwrite_edited)
    print(report(parsed, result, edited, applied=args.apply))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
